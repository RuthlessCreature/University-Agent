import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {installSkills} from './install-skills.mjs';
const root=path.resolve(import.meta.dirname,'..'),source=path.resolve(root,'../University-Skills');
const manifest=JSON.parse(fs.readFileSync(path.join(source,'skills-manifest.json'),'utf8'));
const sha=x=>createHash('sha256').update(x).digest('hex');
const commit=execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
execFileSync('git',['-C',source,'diff','--quiet','HEAD','--','skills','skills-manifest.json']);
installSkills({source,target:path.join(root,'.agents/skills')});
const skills={};
for(const item of manifest.skills){
 const bytes=execFileSync('git',['-C',source,'show',commit+':'+item.path]);
 const localPath=path.join(root,'.agents/skills',item.id,'SKILL.md'),local=fs.readFileSync(localPath);
 if(!bytes.equals(Buffer.from(local.toString('utf8').replace(/\r\n/g,'\n'))))throw Error('Local Skill differs from canonical source: '+item.id);
 fs.writeFileSync(localPath,bytes);
 skills[item.id]={id:item.id,title:item.title,sha256:sha(bytes),content:bytes.toString('utf8'),status:item.status,scope:item.integration_scope||'instruction-only; capabilities depend on available tools'};
}
const pack={repository:'RuthlessCreature/University-Skills',commit,skills};
const fingerprint=sha(JSON.stringify(pack));
fs.mkdirSync(path.join(root,'src/generated'),{recursive:true});
fs.writeFileSync(path.join(root,'src/generated/skill-pack.js'),'// Generated by tools/sync-shared-skills.mjs; do not edit.\nexport const SKILL_PACK='+JSON.stringify({...pack,fingerprint},null,2)+';\n');
fs.writeFileSync(path.join(root,'skills-lock.json'),JSON.stringify({repository:'https://github.com/'+pack.repository,commit,fingerprint,skills:Object.fromEntries(Object.entries(skills).map(([k,v])=>[k,v.sha256])),scope:'identical SKILL.md bytes in local Codex folders and Worker prompts; available execution tools differ'},null,2)+'\n');
console.log('Shared Skill pack verified:',Object.keys(skills).length,'skills;',commit,';',fingerprint);
